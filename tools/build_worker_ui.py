#!/usr/bin/env python3
"""Bundle titan.py's browser UI (UI_HTML) and TITAN.md into the Cloudflare Worker.

Writes cloudflare/src/ui.js and cloudflare/src/seed.js so both editions share the same page
and the Worker starts with the same knowledge. Run after editing UI_HTML or TITAN.md.
"""
import ast
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = root / "cloudflare" / "src"
tree = ast.parse((root / "titan.py").read_text(encoding="utf-8"))
html = next(n.value.value for n in tree.body
            if isinstance(n, ast.Assign) and any(getattr(t, "id", None) == "UI_HTML" for t in n.targets))
seed = (root / "TITAN.md").read_text(encoding="utf-8")
for name, value, what in (("ui.js", html, "titan.py's UI_HTML"), ("seed.js", seed, "TITAN.md")):
    out = src / name
    out.write_text(f"// Generated by tools/build_worker_ui.py from {what}. Don't edit by hand.\n"
                   f"export default {json.dumps(value, ensure_ascii=False)};\n", encoding="utf-8")
    print(f"wrote {out.relative_to(root)} ({len(value)} chars)")
