#!/usr/bin/env python3
"""Copy the browser UI from titan.py (UI_HTML) into cloudflare/src/ui.js so both editions share it."""
import ast
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
tree = ast.parse((root / "titan.py").read_text(encoding="utf-8"))
html = next(n.value.value for n in tree.body
            if isinstance(n, ast.Assign) and any(getattr(t, "id", None) == "UI_HTML" for t in n.targets))
out = root / "cloudflare" / "src" / "ui.js"
out.write_text("// Generated by tools/build_worker_ui.py from titan.py's UI_HTML. Don't edit by hand.\n"
               f"export default {json.dumps(html)};\n", encoding="utf-8")
print(f"wrote {out.relative_to(root)} ({len(html)} chars)")
