#!/usr/bin/env node
// Bundle the Cloudflare edition into public/_worker.js for Cloudflare Pages ("advanced mode").
// The bundle is self-contained and committed, so Pages needs no build step.
// Run `npm run build` after changing cloudflare/src (or titan.py's UI / TITAN.md, via build_worker_ui.py).
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const options = {
  entryPoints: [path.join(root, "cloudflare/src/index.js")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  legalComments: "none",
  banner: { js: "// Generated by tools/build_pages.mjs from cloudflare/src. Don't edit by hand." },
  logLevel: "silent",
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await build({ ...options, outfile: path.join(root, "public/_worker.js") });
  console.log("wrote public/_worker.js");
}
